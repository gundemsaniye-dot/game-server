export function applySpans(data, spans, gid, width = 32, height = 18) {
  for (const [row, firstColumn, lastColumn] of spans) {
    if (row < 0 || row >= height || firstColumn < 0 || lastColumn >= width || firstColumn > lastColumn) {
      throw new Error(`Invalid navigation span: ${JSON.stringify([row, firstColumn, lastColumn])}`);
    }
    for (let column = firstColumn; column <= lastColumn; column += 1) {
      data[row * width + column] = gid;
    }
  }
}
